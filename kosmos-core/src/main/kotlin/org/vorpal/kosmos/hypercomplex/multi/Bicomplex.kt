package org.vorpal.kosmos.hypercomplex.multi

import org.vorpal.kosmos.algebra.structures.CD
import org.vorpal.kosmos.core.math.Real
import org.vorpal.kosmos.hypercomplex.complex.Complex
import org.vorpal.kosmos.hypercomplex.complex.ComplexAlgebras
import org.vorpal.kosmos.hypercomplex.complex.RealComplex
import org.vorpal.kosmos.hypercomplex.complex.complex

/**
 * A bicomplex number over a commutative base ring [R], also historically known as a tessarine.
 * ```text
 * Bicomplex(R) = Complex(R) ⊗_R Complex(R) ≅ Complex(Complex(R)).
 * ```
 * This is the commutative algebra of rank 4 over `R` generated by two commuting imaginary units
 * `i` and `j` with `i² = j² = -1`. Their product `k = ij` satisfies `k² = +1`.
 *
 * Representation:
 * A bicomplex number is stored in the *standard basis* as a Cayley-Dickson pair
 * ```text
 * z = z1 + z2·j,   z1, z2 ∈ Complex(R),
 * ```
 * i.e. `Complex(R)[j]/(j² + 1)`, the Cayley-Dickson doubling of `Complex(R)` equipped with the
 * *trivial* involution at `σ = 1` (see
 * [org.vorpal.kosmos.algebra.structures.CayleyDickson.commutative]). All arithmetic comes from that
 * construction; see [BicomplexAlgebras].
 *
 * The classical case has a name: [RealBicomplex] `= Bicomplex<Real>`, the algebra `𝔹 = ℂ ⊗_ℝ ℂ`.
 *
 * [Bicomplex] is a value class rather than a typealias of [CD] so that it is a distinct Kotlin type
 * from the other algebras built on pairs of complex numbers.
 *
 * Idempotent coordinates:
 * The two maps
 * ```text
 * 𝛂 = z1 + i·z2,   𝜷 = z1 - i·z2
 * ```
 * are ring homomorphisms `Bicomplex(R) → Complex(R)` over *any* commutative base ring; see
 * [BicomplexAlgebras.firstProjection] and [BicomplexAlgebras.secondProjection].
 *
 * When 2 is invertible in `R`, the bicomplex algebra moreover splits as a product,
 * ```text
 * Bicomplex(R) ≅ Complex(R) × Complex(R),   z ↦ (𝛂, 𝜷).
 * ```
 * The orthogonal idempotents `e₁ = (1 - ij)/2` and `e₂ = (1 + ij)/2` give the decomposition
 * `z = 𝛂·e₁ + 𝜷·e₂`, and in these coordinates multiplication is componentwise; see
 * [BicomplexAlgebras.idempotentIsomorphism] and [BicomplexAlgebras.ofIdempotent].
 *
 * The projections exist over every base, but the inverse decomposition needs `1/2`. Without it the
 * combined map `z ↦ (𝛂, 𝜷)` is not an isomorphism: over ℤ it is injective but not surjective, and
 * over `𝔽₂`, where `+i = -i`, the two projections coincide and it is not even injective.
 *
 * Over ℝ the coordinates are also available as the views [alpha], [beta] and [idempotent].
 *
 * Tessarines:
 * The tessarines are the same algebra in a different basis, not a different number system. They are
 * usually presented with commuting generators `i² = -1` and `j_tess² = +1`. The two presentations
 * are related by
 * ```text
 * j_tess = i·j,        j_tess² = i²·j² = (-1)(-1) = +1,
 * j      = -i·j_tess,
 * ```
 * so `j_tess` is the unit called `k` here. This change of basis works over every commutative ring,
 * with no need for 2 to be invertible.
 *
 * The term "bibinarion" may also be used for this algebra when viewed as a
 * second binarion construction.
 */
@JvmInline
value class Bicomplex<R : Any>(val cd: CD<Complex<R>>) {

    /** The first standard component `z1` of `z1 + z2·j`. */
    val z1: Complex<R>
        get() = cd.a

    /** The second standard component `z2` of `z1 + z2·j`. */
    val z2: Complex<R>
        get() = cd.b

    /** The standard coefficients of `a + bi + cj + dk`. */
    val a: R
        get() = z1.re
    val b: R
        get() = z1.im
    val c: R
        get() = z2.re
    val d: R
        get() = z2.im

    /**
     * Destructuring gives the two standard complex components: `val (z1, z2) = z`. The four scalar
     * coordinates are available through [coefficients].
     */
    operator fun component1(): Complex<R> = z1
    operator fun component2(): Complex<R> = z2

    /**
     * Return the standard complex components `(z1, z2)` of the bicomplex number.
     */
    fun standard(): Pair<Complex<R>, Complex<R>> =
        z1 to z2

    /**
     * Returns the standard coefficients `[a, b, c, d]`:
     * ```text
     * z = (a + bi) + (c + di)j
     * ```
     */
    fun coefficients(): List<R> =
        listOf(a, b, c, d)

    override fun toString(): String =
        "Bicomplex(z1=$z1, z2=$z2)"

    companion object {
        /**
         * The bicomplex number `z1 + z2·j`.
         */
        fun <R : Any> ofStandard(z1: Complex<R>, z2: Complex<R>): Bicomplex<R> =
            Bicomplex(CD(z1, z2))

        /**
         * The bicomplex number `a + bi + cj + dk`.
         */
        fun <R : Any> ofStandard(a: R, b: R, c: R, d: R): Bicomplex<R> =
            ofStandard(complex(a, b), complex(c, d))
    }
}

/** The bicomplex numbers `𝔹 = ℂ ⊗_ℝ ℂ`. */
typealias RealBicomplex = Bicomplex<Real>

/** The first idempotent coordinate `𝛂 = z1 + i·z2 = (a - d) + (b + c)i`. */
val RealBicomplex.alpha: RealComplex
    get() = complex(a - d, b + c)

/** The second idempotent coordinate `𝜷 = z1 - i·z2 = (a + d) + (b - c)i`. */
val RealBicomplex.beta: RealComplex
    get() = complex(a + d, b - c)

/**
 * Return the idempotent complex components `(𝛂, 𝜷)` of the bicomplex number.
 */
fun RealBicomplex.idempotent(): Pair<RealComplex, RealComplex> =
    alpha to beta

/**
 * A real bicomplex number lies in the null cone iff at least one idempotent
 * component is zero.
 *
 * Equivalently, it is not a unit, and its determinant-like norm
 * `normByConj2 = z1² + z2² = 𝛂𝜷` vanishes.
 *
 * This includes zero.
 *
 * This predicate, [isUnit] and [isZeroDivisor] are deliberately specific to ℝ. Over a general base
 * ring, "both idempotent coordinates are nonzero" does not imply "unit": over ℤ the element with
 * coordinates `(2, 2)` is nonzero in both, yet `2` is not invertible in `ℤ[i]` (and is not a zero
 * divisor either). There the right notion is that both coordinates are *units* of `Complex(R)`.
 *
 * The comparison with zero is exact (strict floating-point equality): this classifies the represented
 * values, so an invertible element is never reported as a zero divisor merely for being close to the
 * null cone. For numerical invertibility use `BicomplexCommutativeRing.hasReciprocal`.
 */
fun RealBicomplex.isInNullCone(): Boolean {
    val zero = ComplexAlgebras.ComplexField.zero
    val eq = ComplexAlgebras.eqComplexStrict
    return eq(alpha, zero) || eq(beta, zero)
}

/**
 * A bicomplex number is a nonzero zero divisor iff it is nonzero and lies
 * in the null cone.
 */
fun RealBicomplex.isZeroDivisor(): Boolean =
    coefficients().any { it != 0.0 } && isInNullCone()

/**
 * A bicomplex number is a unit iff it is not in the null cone.
 */
fun RealBicomplex.isUnit(): Boolean =
    !isInNullCone()
